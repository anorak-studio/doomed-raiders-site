export function pixelIconPath(name: string): string {
  const rows = ICONS[name] || [];
  let rects = "";
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) if (row[x] === "#") rects += `M${x} ${y}h1v1h-1z`;
  });
  return rects;
}

export function biomeArrowPath(dir: "prev" | "next"): string {
  return dir === "prev"
    ? "M4 0h2v2H4zM2 2h2v2H2zM0 4h2v3H0zM2 7h2v2H2zM4 9h2v2H4z"
    : "M1 0h2v2H1zM3 2h2v2H3zM5 4h2v3H5zM3 7h2v2H3zM1 9h2v2H1z";
}
